// Generates a throwaway bank of TRANSPARENTLY FAKE questions so the practice
// engine can be tested end to end on the live site:
//
//     node scripts/build-synthetic-seed.mjs
//
// Writes two files into docs/tmp (which is gitignored):
//
//     synthetic-questions.sql  — insert them
//     synthetic-cleanup.sql    — delete every one, and prove it
//
// WHY THE QUESTIONS ARE NOT ABOUT AVIATION. An approved row is servable to
// any student. The harm in unreviewed content is a learner absorbing a wrong
// fact, so these contain no aviation claims at all — a student who somehow saw
// one would see obvious scaffolding and report it, rather than learn something
// false. That is the whole point of writing them this way.
//
// DELETE THEM WHEN THE TEST IS DONE. The cleanup file is generated alongside
// so it is never a thing to write under pressure.

import { writeFileSync, mkdirSync } from "node:fs";
import { TEST_BLUEPRINT } from "../src/lib/practice/assemble.ts";

const MARKER = "SYNTHETIC TEST DATA — DELETE BEFORE ANY REAL STUDENT";
const OUT_DIR = "docs/tmp";

// Enough that a full 60-question test can be assembled twice without the
// recency rule relaxing: the heaviest area needs 8 per test.
const PER_AREA = 20;

function lit(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const rows = [];

for (const { area } of TEST_BLUEPRINT) {
  for (let i = 1; i <= PER_AREA; i += 1) {
    // The correct choice moves around so the engine's shuffling is being
    // exercised against something that is not always in the same slot.
    const correct = ["A", "B", "C"][i % 3];

    const choices = {
      A: correct === "A" ? "test answer" : "not the test answer (first decoy)",
      B: correct === "B" ? "test answer" : "not the test answer (second decoy)",
      C: correct === "C" ? "test answer" : "not the test answer (third decoy)",
    };

    rows.push(
      `  (${lit(`SYNTHETIC.${area.slice(0, 3).toUpperCase()}.${i}`)}, ${lit(area)}, ` +
        `${lit(`Placeholder question ${i} for "${area}". This is NOT a real aviation question — it exists only to test the practice test software. Choose the option that says "test answer".`)}, ` +
        `${lit(choices.A)}, ${lit(choices.B)}, ${lit(choices.C)}, ${lit(correct)}, ` +
        `${lit('This question is scaffolding, not teaching. If you are seeing it as a student, something has gone wrong and we would like to know — demetrius@pilotpathway.ai.')}, ` +
        `${lit(MARKER)}, ${lit(MARKER)})`,
    );
  }
}

const insert = `-- SYNTHETIC PRACTICE QUESTIONS — NOT REAL CONTENT.
--
-- Generated by scripts/build-synthetic-seed.mjs so the practice engine can be
-- tested on the live site before any CFI-reviewed question exists.
--
-- ${rows.length} questions, ${PER_AREA} per knowledge area.
--
-- These are marked cfi_approved, which means students CAN be served them.
-- They contain no aviation claims, so the worst case is confusion rather than
-- a wrong fact — but they must still be deleted the moment the test is done.
-- Run docs/tmp/synthetic-cleanup.sql to do that.

insert into public.question_bank
  (acs_code, knowledge_area, stem, choice_a, choice_b, choice_c, correct_choice,
   explanation, authored_by, reviewed_by)
values
${rows.join(",\n")};

update public.question_bank
set review_status = 'cfi_approved', reviewed_at = now()
where reviewed_by = ${lit(MARKER)};

-- Expect: ${rows.length} synthetic questions, and 0 real ones (nothing else is approved yet).
select
  count(*) filter (where reviewed_by = ${lit(MARKER)}) as synthetic_approved,
  count(*) filter (where review_status = 'cfi_approved' and reviewed_by is distinct from ${lit(MARKER)}) as real_approved
from public.question_bank;
`;

const cleanup = `-- Removes every synthetic practice question, and everything that referenced
-- them. Run this as soon as the end-to-end test is finished.
--
-- Order matters: practice_answers references question_bank with ON DELETE
-- RESTRICT, deliberately, so a question can never vanish from under a real
-- student's completed attempt. The synthetic attempts have to go first.

delete from public.question_exposure
where question_id in (
  select id from public.question_bank where reviewed_by = ${lit(MARKER)}
);

delete from public.practice_answers
where question_id in (
  select id from public.question_bank where reviewed_by = ${lit(MARKER)}
);

-- Any attempt left with no questions was made entirely of synthetic ones:
-- a real attempt always has its answer rows written when it starts. NOT
-- EXISTS rather than NOT IN, which returns nothing at all if the subquery
-- ever yields a null and would silently delete none of them.
delete from public.practice_attempts a
where not exists (
  select 1 from public.practice_answers ans where ans.attempt_id = a.id
);

delete from public.question_bank
where reviewed_by = ${lit(MARKER)};

-- Expect every count to be 0.
select
  (select count(*) from public.question_bank where reviewed_by = ${lit(MARKER)}) as synthetic_questions_left,
  (select count(*) from public.question_bank where review_status = 'cfi_approved') as approved_questions_left,
  (select count(*) from public.practice_attempts) as attempts_left,
  (select count(*) from public.question_exposure) as exposure_rows_left;
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(`${OUT_DIR}/synthetic-questions.sql`, insert, "utf8");
writeFileSync(`${OUT_DIR}/synthetic-cleanup.sql`, cleanup, "utf8");

console.log(`build-synthetic-seed: ${rows.length} questions across ${TEST_BLUEPRINT.length} areas`);
console.log(`  ${OUT_DIR}/synthetic-questions.sql`);
console.log(`  ${OUT_DIR}/synthetic-cleanup.sql`);
console.log("  every one is marked, transparently fake, and deletable in one run");
