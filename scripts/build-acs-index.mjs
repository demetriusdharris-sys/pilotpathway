// Builds an index of every ACS code from the FAA's own document:
//
//     node scripts/build-acs-index.mjs
//
// Reads docs/reference/private-pilot-acs.pdf (public domain, kept in the repo
// on purpose) and writes docs/reference/acs-codes.json.
//
// WHY THIS EXISTS. Every practice question carries an ACS code, and codes are
// revision-specific — a stale or invented one is the sort of mistake a student
// pays for in front of an examiner. With an index, scripts/import-questions.mjs
// can refuse a code the FAA document does not contain, which turns "do not
// invent codes" from a rule someone has to remember into one the pipeline
// enforces.
//
// Plain Node: zlib is in the standard library, so this adds nothing to the
// locked stack. It is a deliberately small PDF reader — it pulls the text out
// of Flate-compressed content streams and nothing more.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { inflateSync, constants } from "node:zlib";

const PDF = "docs/reference/private-pilot-acs.pdf";
const OUT = "docs/reference/acs-codes.json";

if (!existsSync(PDF)) {
  console.error(`build-acs-index: ${PDF} is missing.`);
  console.error(
    "  Download the Private Pilot ACS from faa.gov and save it there. It is public domain.",
  );
  process.exit(1);
}

const data = readFileSync(PDF);

/** Every Flate-compressed stream in the file, decompressed and concatenated. */
function readStreams(buffer) {
  const text = [];
  const marker = Buffer.from("stream");

  let index = buffer.indexOf(marker);

  while (index !== -1) {
    let start = index + marker.length;
    if (buffer[start] === 0x0d) start += 1;
    if (buffer[start] === 0x0a) start += 1;

    const end = buffer.indexOf(Buffer.from("endstream"), start);
    if (end === -1) break;

    try {
      // Z_SYNC_FLUSH because a PDF content stream is followed by the bytes
      // that end the object, and Node's inflate treats those as a corrupt
      // tail where Python's simply stops. Without this, almost every stream
      // in the file is skipped and the index comes back empty.
      text.push(
        inflateSync(buffer.subarray(start, end), {
          finishFlush: constants.Z_SYNC_FLUSH,
        }).toString("latin1"),
      );
    } catch {
      // Not a Flate stream — images, fonts, anything else. Skipped silently:
      // this reader only wants text.
    }

    // Past the whole "endstream" token. Resuming at `end` finds the "stream"
    // inside that word, which then pairs with the NEXT endstream and swallows
    // every real stream in between — 291 of 293 were being skipped.
    index = buffer.indexOf(marker, end + "endstream".length);
  }

  return text.join("\n");
}

const raw = readStreams(data);

// PDF text lives inside parentheses in the content stream. Pull those out and
// join them, then strip the language tags the FAA's generator interleaves.
const pieces = [];
for (const match of raw.matchAll(/\((?:\\.|[^\\()])*\)/gs)) {
  pieces.push(
    match[0]
      .slice(1, -1)
      .replace(/\\([()\\])/g, "$1")
      .replace(/\\[nrt]/g, " "),
  );
}

const flat = pieces.join("").replace(/en-US/g, "").replace(/\s+/g, " ");

// PA.<area>.<task>.<K|R|S><number><optional letter>
const CODE = /PA\.(?:X{0,3})(?:IX|IV|V?I{0,3})\.[A-Z]\.([KRS])(\d+)([a-z]?)/g;

const codes = new Map();
const matches = [...flat.matchAll(CODE)];

matches.forEach((match, i) => {
  const code = match[0];
  const from = match.index + code.length;
  const to = i + 1 < matches.length ? matches[i + 1].index : flat.length;

  // The text belonging to a code runs until the next code starts. Trimmed to a
  // sentence or so, because the index exists to identify a code, not to
  // reproduce the ACS.
  const description = flat
    .slice(from, Math.min(to, from + 400))
    .replace(/^[\s.:—-]+/, "")
    .replace(/^[a-z]\.\s*/, "")
    .trim();

  if (!codes.has(code) || (codes.get(code) ?? "").length < description.length) {
    codes.set(code, description.slice(0, 300));
  }
});

if (codes.size === 0) {
  console.error(
    "build-acs-index: no ACS codes found — the PDF may be a scan rather than text, or its structure changed.",
  );
  process.exit(1);
}

const sorted = [...codes.entries()].sort(([a], [b]) => a.localeCompare(b));

const index = {
  source: PDF,
  note: "Generated by scripts/build-acs-index.mjs from the FAA's Private Pilot ACS. Regenerate when the ACS is revised.",
  generatedAt: new Date().toISOString().slice(0, 10),
  codeCount: sorted.length,
  codes: Object.fromEntries(sorted),
};

writeFileSync(OUT, `${JSON.stringify(index, null, 2)}\n`, "utf8");

const areas = new Set(sorted.map(([code]) => code.split(".").slice(0, 2).join(".")));
const tasks = new Set(sorted.map(([code]) => code.split(".").slice(0, 3).join(".")));

console.log(`build-acs-index: ${sorted.length} codes → ${OUT}`);
console.log(`  ${areas.size} areas of operation, ${tasks.size} tasks`);
console.log(
  `  knowledge ${sorted.filter(([c]) => /\.K\d/.test(c)).length}, ` +
    `risk management ${sorted.filter(([c]) => /\.R\d/.test(c)).length}, ` +
    `skill ${sorted.filter(([c]) => /\.S\d/.test(c)).length}`,
);
